# src/agents/report_writer.py
"""
Report writer node — compiles the final investment research report.
"""
from langchain_core.messages import HumanMessage, AIMessage
from langchain_google_genai import ChatGoogleGenerativeAI

from config.settings import GEMINI_API_KEY, GEMINI_MODEL
from src.agents.state import ResearchState
from src.citations.citation_tracker import CitationTracker


REPORT_WRITER_PROMPT = """You are a professional Investment Research Report Writer.

Create a comprehensive, institutional-quality investment research report. 

Structure:
1. **Executive Summary** — Key findings in 3-4 sentences
2. **Company Overview** — Business description, market position, competitive advantages
3. **Financial Analysis** 
   - Revenue & Profitability trends
   - Balance Sheet health
   - Cash Flow analysis
   - Key financial ratios with peer comparison
4. **Valuation Assessment** — Current valuation vs. fair value estimate
5. **Growth Catalysts** — What could drive upside
6. **Risk Factors** — Key downside risks
7. **Recent Developments** — Latest news and events
8. **Investment Thesis** — Bull case vs. Bear case
9. **Conclusion & Recommendation** — Clear actionable takeaway

Requirements:
- Every factual claim must have a citation [1], [2], etc.
- Include specific numbers and metrics
- Be balanced — present both sides
- Professional, concise language
- Include a disclaimer that this is AI-generated research

IMPORTANT: At the end, include a "Sources & Citations" section listing all references.
"""


def create_report_writer_node():
    """Create the report writer node function for LangGraph."""

    llm = ChatGoogleGenerativeAI(
        model=GEMINI_MODEL,
        google_api_key=GEMINI_API_KEY,
        temperature=0.3,
    )

    async def report_writer_node(state: ResearchState) -> dict:
        """Report writer node that compiles the final research report."""
        query = state["query"]
        ticker = state["ticker"]
        analysis = state.get("analysis", "")
        research_data = state.get("research_data", {})
        fact_check = state.get("fact_check_results", {})
        citations = state.get("citations", [])

        # Format citations for the report
        citations_text = ""
        for i, cite in enumerate(citations, 1):
            citations_text += (
                f"[{i}] [{cite.get('source_type', 'unknown').upper()}] "
                f"{cite.get('source_name', 'Unknown')}\n"
                f"    Excerpt: \"{cite.get('excerpt', '')[:100]}...\"\n\n"
            )

        # Data summary
        data_summary = ""
        for key, value in research_data.items():
            if isinstance(value, str):
                data_summary += f"\n### {key.replace('_', ' ').title()}\n{value[:2000]}\n"

        prompt = f"""{REPORT_WRITER_PROMPT}

**Research Query:** {query}
**Company Ticker:** {ticker}

**Analyst's Analysis:**
{analysis}

**Fact-Check Report:**
{fact_check.get('report', 'N/A')}

**Raw Research Data:**
{data_summary[:10000]}

**Available Citations:**
{citations_text}

Generate the complete investment research report now.
"""

        response = await llm.ainvoke([HumanMessage(content=prompt)])

        report = response.content

        # Add disclaimer
        disclaimer = (
            "\n\n---\n"
            "**⚠️ Disclaimer:** This report was generated by FinResearch AI, an AI-powered "
            "research assistant. It is for informational purposes only and does not constitute "
            "investment advice. Always conduct your own due diligence and consult with a "
            "qualified financial advisor before making investment decisions. Data may be "
            "delayed or incomplete.\n"
            f"\n*Report generated on: {__import__('datetime').datetime.now().strftime('%Y-%m-%d %H:%M:%S UTC')}*\n"
        )

        final_report = report + disclaimer

        return {
            "final_report": final_report,
            "current_phase": "report_complete",
            "messages": [
                AIMessage(content=f"Research report complete for {ticker}.")
            ],
        }

    return report_writer_node